"""Real client IP restoration (ngx_http_realip_module) conf rendering.

Two hops need it:
- bench nginx always sees the global proxy's frontend-network address, so it
  trusts that subnet and restores the client from X-Real-IP (which the proxy
  sets from its own, possibly CDN-corrected, remote_addr);
- the global nginx-proxy only needs it behind a CDN or external load
  balancer, where remote_addr is the CDN edge and the client is in a header.
"""

import ipaddress
from pathlib import Path

_MARKER = "# fm:real-ip"
_TRUST_MARKER = "# fm:forwarded-trust"

# The overlay `fm services trusted-proxies` maintains in the global proxy's conf.d.
PROXY_CONF_FILENAME = "fm-real-ip.conf"

# The second file that overlay drives: the scheme decision and the published HTTPS port, both
# read by fm's own redirect blocks. Separate from the real-ip conf because it must exist even
# when nothing is trusted -- `$fm_client_scheme` has to be defined for every host, or the
# per-domain redirect blocks fail to parse and the proxy refuses to start.
PROXY_TRUST_CONF_FILENAME = "fm-forwarded-trust.conf"

